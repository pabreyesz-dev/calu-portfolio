export function applyTranslations(lang: 'es' | 'en') {
  const t = translations[lang];
  document.documentElement.setAttribute('lang', lang);
  document.documentElement.setAttribute('data-language', lang);

  // Actualizar elementos con data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (key && t[key as keyof typeof t]) {
      // Si contiene HTML seguro (como bioP1) usar innerHTML, si no textContent
      // Para simplificar, usaremos innerHTML para permitir etiquetas como <strong>
      el.innerHTML = t[key as keyof typeof t];

      // Manejar placeholders si es un input/textarea
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        (el as HTMLInputElement).placeholder = t[key as keyof typeof t];
      }
    }
  });
}

export function getCurrentLanguage(): 'es' | 'en' {
  if (typeof localStorage === 'undefined') return 'es';
  return (localStorage.getItem('language') || 'es') as 'es' | 'en';
}
